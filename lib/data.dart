double _original(double price) {
  final raw = price * 1.6;
  if (price < 10) return double.parse(raw.toStringAsFixed(1));
  if (price < 1000) return double.parse(raw.toStringAsFixed(0));
  return (raw / 100).round() * 100.0;
}

